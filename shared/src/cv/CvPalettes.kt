/**
 * Пара схем — светлой и тёмной — для одной палитры.
 */
data class CvPaletteSpec(
    val light: ColorScheme,
    val dark: ColorScheme,
)

/**
 * Палитра CV: одна из схем «основных цветов». По умолчанию — фиолетовая.
 */
enum class CvPalette(private val spec: CvPaletteSpec, val label: String) {
    /** Фиолетовая. */
    Purple(CvPaletteSpec(PurpleLight, PurpleDark), "Фиолетовая"),
    /** Песчаная. */
    Sand(CvPaletteSpec(SandLight, SandDark), "Песчаная"),
    /** Зелёная. */
    Green(CvPaletteSpec(GreenLight, GreenDark), "Зелёная"),
    /** Небесная. */
    Sky(CvPaletteSpec(SkyLight, SkyDark), "Небесная"),
    /** Лавандовая. */
    Lavender(CvPaletteSpec(LavenderLight, LavenderDark), "Лавандовая"),
    /** Розовая. */
    Pink(CvPaletteSpec(PinkLight, PinkDark), "Розовая");

    /** Схема под выбранный режим темы. */
    fun scheme(darkTheme: Boolean): ColorScheme = if (darkTheme) spec.dark else spec.light

    /** Кружок-превью в настройках: пастельный контейнер светлой схемы. */
    val swatch: Color get() = spec.light.primaryContainer

    /** Цвет галочки на кружке. */
    val onSwatch: Color get() = spec.light.onPrimaryContainer
}
